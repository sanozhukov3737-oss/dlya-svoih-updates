def sections(body):
    result = []
    heading = ''
    buf = []
    for line in body.splitlines():
        if line.startswith('## '):
            if buf or heading:
                result.append((heading, '\n'.join(buf).strip()))
            heading, buf = line[3:].strip(), []
        else:
            buf.append(line)
    if buf or heading:
        result.append((heading, '\n'.join(buf).strip()))
    return result


