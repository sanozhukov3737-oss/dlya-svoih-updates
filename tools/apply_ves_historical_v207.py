def save_asset(raster: Image.Image, stem: str) -> dict:
    full_rel = f"images/{stem}.webp"
    thumb_rel = f"thumbs/{stem}.webp"
    full = ASSETS / full_rel
    thumb = ASSETS / thumb_rel
    full.parent.mkdir(parents=True, exist_ok=True)
    thumb.parent.mkdir(parents=True, exist_ok=True)
    raster.save(full, "WEBP", quality=88, method=6)
    miniature = raster.copy()
    miniature.thumbnail((256, 256), Image.Resampling.LANCZOS)
    miniature.save(thumb, "WEBP", quality=84, method=6)
    return {
        "localPath": full_rel,
        "thumbnailPath": thumb_rel,
        "width": raster.width,
        "height": raster.height,
        "fullSha256": hashlib.sha256(full.read_bytes()).hexdigest(),
        "thumbnailSha256": hashlib.sha256(thumb.read_bytes()).hexdigest(),
    }


def main() -> None:
    WORK.mkdir(parents=True, exist_ok=True)
    data = json.loads(PRODUCTION_CATALOG.read_text(encoding="utf-8"))
    if data["contentVersion"] not in (TARGET_VERSION - 1, TARGET_VERSION):
        raise RuntimeError(f"Expected catalog {TARGET_VERSION - 1} or {TARGET_VERSION}, got {data['contentVersion']}")
    my_ids = {spec["id"] for spec in CARDS}
    data["cards"] = [card for card in data["cards"] if card["id"] not in my_ids]
    next_rowid = max(card["rowid"] for card in data["cards"]) + 1
    entries = []
    new_cards = []
    for index, spec in enumerate(CARDS):
        images = []
        for position, (stem, figure, description) in enumerate(spec["images"]):
            raster = Image.open(BANK / f"{stem}.jpg").convert("RGB")
            if stem in ("ves-zapal-4", "ves-zapal-5"):
                raster = raster.crop((0, int(raster.height * 0.05), raster.width, raster.height))
            raster.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
            asset = save_asset(raster, stem)
            images.append({
                "id": stem,
                "localPath": asset["localPath"],
                "caption": cap(figure, description, spec["article"]),
                "width": asset["width"],
                "height": asset["height"],
                "position": position,
                "thumbnailPath": asset["thumbnailPath"],
            })
            entries.append({"cardId": spec["id"], "stem": stem, **asset})
        card = {
            "rowid": next_rowid + index,
            "id": spec["id"],
            "section": "AMMUNITION",
            "categoryId": spec["categoryId"],
            "title": spec["title"],
            "summary": spec["summary"],
            "body": spec["body"],
            "thumbnailPath": images[0]["thumbnailPath"],
            "contentStatus": "source_only",
            "reviewedAt": None,
            "archived": 0,
            "modelStatus": "source-listed",
            "sourceGrade": "B",
            "verifiedAt": None,
            "tags": spec["tags"],
            "countries": spec["countries"],
            "images": images,
            "sources": [{**spec["source"], "id": f"{spec['source']['id']}-{spec['id']}"}],
        }
        new_cards.append(card)
    data["cards"].extend(new_cards)
    data["contentVersion"] = TARGET_VERSION
    data["catalogVersion"] = TARGET_VERSION
