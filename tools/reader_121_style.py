def polish(text, notes):
    paragraphs=[]
    for p in re.split(r'\n\s*\n',text):
        p=p.strip()
        if not p: continue
        if p.startswith('|') or p.startswith('### '):
            paragraphs.append(p); continue
        def archive(m):notes.append(m[0]);return ''
        p=CITATION.sub(archive,p)
        for a,b in REPAIRS.items():p=p.replace(a,b)
        p=re.sub(r'^(.{1,90}?) (?:в источнике |в документе )?(?:представлена|представлен|представлены) (?:в документе |в описании )?как ',r'\1 — ',p)
        p=re.sub(r'Калибр (\d+ мм), но не приводит длину изделия\.',r'Калибр — \1; длина изделия не указана.',p)
        p=re.sub(r'^(.*?) — (.*?) миномётная мина, (\d+ мм)\.',r'\1 — \3 \2 миномётная мина.',p)
        # Avoid a duplicated caliber already present in the model's full name.
        p=re.sub(r'^(\d+)-мм ([^—]+) — \1 мм ',r'\1-мм \2 — ',p)
        p=re.sub(r'^Период: (.+?)[.]?$',r'Модель относится к периоду: \1.',p)
        p=re.sub(r'\s+([,.;])',r'\1',p)
        p=re.sub(r' {2,}',' ',p).strip()
        kept=[]
        for s in re.split(r'(?<=[.!?])\s+(?=[А-ЯЁA-Z«])',p):
            if EDITORIAL.match(s):notes.append(s)
            else:kept.append(s)
        if kept:paragraphs.append(' '.join(kept))
    return '\n\n'.join(paragraphs)

def consolidate_materials(ps):
    """Eliminate repeated isolated material sentences, not model-specific claims."""
    text=' '.join(ps)
    stems=(('пластмасс','пластик'),('металл',),('чугун',),('дерев',),('бакелит',))
    out=[]
    for p in ps:
        if re.fullmatch(r'Материал корпуса — [^.]+\.',p):
            rest=text.replace(p,'',1).lower()
            groups=[g for g in stems if any(s in p.lower() for s in g)]
            if groups and any(any(s in rest for s in g) for g in groups):continue
        out.append(p)
    return out

